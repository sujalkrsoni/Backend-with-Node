import bcryptjs from "bcryptjs";

const salt = await bcryptjs.genSalt(10);
console.log(salt) // $2b$10$b/T.99qxpYBBTR2VYCzrge    $2b : bcryptjs version , $10 : cost factor means how many rounds of hashing will be applied to the password, b/T.99qxpYBBTR2VYCzrge : 22 character random string generated by bcryptjs

const hash = await bcryptjs.hash("password", salt);
console.log(hash)  // $2b$10$nj4pEHXf3UXws5wXQz4EQudzs74HxeoGVF8CrB6lHV4d2UkHe4jt6




