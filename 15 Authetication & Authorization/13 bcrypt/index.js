let storePasswordInDB = "$2b$10$nj4pEHXf3UXws5wXQz4EQudzs74HxeoGVF8CrB6lHV4d2UkHe4jt6"

const saltFromDB = storePasswordInDB.substring(0, 29) // $2b$10$nj4pEHXf3UXws5wXQz4EQ

