const userInputPassword = "password"

const hashOfUserInputPassword = await bcryptjs.hash(userInputPassword, saltFromDB)
const hashOfUserInputPasswordWithoutSalt = hashOfUserInputPassword.substring(29) // udzs74HxeoGVF8CrB6lHV4d2UkHe4jt6
if(hashOfUserInputPasswordWithoutSalt === hashFromDB){
    console.log("Password is correct", hashOfUserInputPasswordWithoutSalt, hashFromDB)
}else{
    console.log("Password is incorrect", hashOfUserInputPasswordWithoutSalt, hashFromDB)
}


